def pad(packet, length=64):
    return packet + bytes([0] * (length - len(packet)))

def send(device, packet_hex):
    data = bytes.fromhex(packet_hex)
    data = pad(data)
    device.write(data)

def main():
    device = hid.device()
    device.open(0x381C, 0x0003)

    print("Device connected")

    while True:
        for idx, pkt in enumerate(LOOP_PACKETS):
            send(device, pkt)
            print("Packet", idx)
            time.sleep(1.1)

if __name__ == "__main__":
    main()